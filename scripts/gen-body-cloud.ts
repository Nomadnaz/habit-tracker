// Regenerates lib/body-cloud-data.ts from the geometry in lib/body-cloud.ts.
// Run after changing the figure: npm run gen:body-cloud
import { writeFileSync } from 'fs';
import { buildCloud, encodeCloud } from '../lib/body-cloud';

const cloud = buildCloud();
const data = encodeCloud(cloud);
writeFileSync(
  'lib/body-cloud-data.ts',
  `// GENERATED by scripts/gen-body-cloud.ts — do not edit. ${cloud.n} points.\nexport const BODY_CLOUD =\n  '${data}';\n`,
);
console.log(`body cloud: ${cloud.n} points, ${data.length} chars`);
